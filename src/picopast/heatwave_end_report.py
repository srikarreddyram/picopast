"""The report for "Storms end heatwaves: the whole record, 1982-2026" (``picopast heatwave-end``)."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from picopast.config import Config

STORM, CTRL = "#2a78d6", "#8d8c85"
NORTH, SOUTH = "#eb6834", "#2a78d6"
INK, MUTED = "#2b2b29", "#6b6a63"


def _pct(v, digits=0) -> str:
    return "n/a" if v is None or not np.isfinite(v) else f"{100 * v:.{digits}f}%"


def _ci(e: dict, key="effect", scale=1.0, digits=2, unit="") -> str:
    v, lo, hi = (e[k] * scale for k in (key, "lo", "hi"))
    return f"{v:+.{digits}f}{unit} [{lo:+.{digits}f}, {hi:+.{digits}f}]"


def _vci(m: dict, scale=1.0, digits=2, unit="") -> str:
    return f"{m['value'] * scale:.{digits}f}{unit} [{m['lo'] * scale:.{digits}f}, {m['hi'] * scale:.{digits}f}]"


def _days(v) -> str:
    return "over 60 d (most never re-warmed within the 60 days)" if v is None or not np.isfinite(v) else f"{v:.0f} d"


def _p(p) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def _style(ax):
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(MUTED)
    ax.tick_params(colors=MUTED, labelsize=8)
    ax.grid(axis="y", color="#e6e5e0", linewidth=0.6)
    ax.set_axisbelow(True)


def plot_survival(res: dict, out: Path) -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    c = res["descriptive"]["D1_curve"]
    days = np.arange(1, len(c["storm"]) + 1)
    fig, ax = plt.subplots(figsize=(6.2, 3.4), dpi=150)
    ax.plot(days, 100 * np.array(c["control"]), color=CTRL, lw=2, label="far from any storm")
    ax.plot(days, 100 * np.array(c["storm"]), color=STORM, lw=2, label="under a storm")
    ax.axvline(5, color=MUTED, lw=0.8, ls=":")
    ax.text(5.3, 96, "D0+5 (the pre-registered day)", color=MUTED, fontsize=7, va="top")
    ax.text(14, 100 * c["control"][13] + 3, "far from any storm", color=CTRL, fontsize=8, va="bottom")
    ax.text(14, 100 * c["storm"][13] - 3, "under a storm", color=STORM, fontsize=8, va="top")
    ax.set_xlim(0.5, days[-1] + 0.5)
    ax.set_ylim(0, 100)
    ax.set_xlabel("days after the storm passed (D0)", color=INK, fontsize=9)
    ax.set_ylabel("heatwave water still in a heatwave (%)", color=INK, fontsize=9)
    _style(ax)
    n = res["points"]["survival_all"]
    ax.set_title(f"Heatwave survival after a storm, 1982–2026 ({n['n_points']:,} points, {n['n_storms']} storms)",
                 color=INK, fontsize=10, loc="left")
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)
    return out


def plot_encounters(res: dict, out: Path) -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.ticker import MaxNLocator

    enc = res["descriptive"]["D2_encounters"]
    fig, axes = plt.subplots(2, 1, figsize=(6.2, 4.4), dpi=150, sharex=True)
    for ax, (reg, color, label) in zip(axes, (("north", NORTH, "North Indian Ocean"),
                                               ("south", SOUTH, "South Indian Ocean"))):
        s = enc[reg]["storms_per_year"]
        yrs = np.array(sorted(int(k) for k in s))
        vals = np.array([s[k] if k in s else s[str(k)] for k in yrs])
        ax.bar(yrs, vals, width=0.8, color=color, edgecolor="white", linewidth=0.5)
        ax.set_ylabel("storms", color=INK, fontsize=8)
        ax.yaxis.set_major_locator(MaxNLocator(integer=True))
        ax.text(0.01, 0.95, f"{label}: storms that crossed heatwave water", transform=ax.transAxes,
                color=INK, fontsize=9, va="top")
        _style(ax)
    axes[-1].set_xlabel("year (2026 incomplete)", color=INK, fontsize=9)
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)
    return out


def report(cfg: Config, res: dict) -> Path:
    figdir = cfg.path("reports") / "figures"
    figdir.mkdir(parents=True, exist_ok=True)
    f_surv = plot_survival(res, figdir / "heatwave_end_survival.png")
    f_enc = plot_encounters(res, figdir / "heatwave_end_encounters.png")
    w1, pt, ds, chk = res["W1"], res["points"], res["descriptive"], res["checks"]
    prim = w1["primary"]
    pooled = prim["pooled"]
    L = ["# Storms end heatwaves: the whole record, 1982–2026", "",
         "Generated by `picopast heatwave-end`. Rules fixed before any of this was computed: "
         "[the pre-registration](../cyclone_heatwave_preregistration.md), section \"Storms end heatwaves\" "
         "(committed 28 November 2026). The bloom question (RQ2) is closed and is not part of this report.", ""]

    # ---- checks
    L += ["## Checks, run before any result was read", ""]
    for reg in ("north", "south"):
        c = chk[reg]
        fl = "; ".join(f"`{k}`: {v['mismatch']:,} of {v['cell_days']:,} cell-days differ"
                       + ("" if v["same_grid"] else " (different grid)") for k, v in c["flags"].items())
        sv = c["survival"]
        L.append(f"- **{reg.title()}** (record {c['record'][0]} to {c['record'][1]}). Heatwave flags against the "
                 f"storm-table caches: {fl}. Survival against the stored tables, {sv['matched_points']:,} points: "
                 f"storm share {sv['survival_storm']['mismatch']} mismatches, control share "
                 f"{sv['survival_control']['mismatch']} mismatches.")
    L.append("")

    # ---- the answer
    a = pooled["all"]
    s1, s2, s3, s4 = (pt[k] for k in ("S1", "S2", "S3", "S4"))
    L += ["## The answer", "",
          f"- **W1 (primary): {pooled['verdict']}.**",
          f"  - Over 1982–2026, a heatwave cell under a storm is **{a['hr']['value']:.1f} times** as likely "
          f"to end that day as one elsewhere in the same basin, month and latitude band "
          f"(rate ratio {_vci(a['hr'], digits=2)}).",
          f"  - Stronger storms do more: {_vci(pooled['64 kt and above']['hr'], digits=1)} at 64 kt and above, "
          f"{_vci(pooled['34-63 kt']['hr'], digits=1)} below.",
          f"  - But storms touch only {_pct(a['exposed_share_of_days']['value'], 2)} of heatwave cell-days, so "
          f"they account for only **{_pct(a['share']['value'], 1)}** of all heatwave endings "
          f"[{_pct(a['share']['lo'], 1)}, {_pct(a['share']['hi'], 1)}]: a strong but rare way for a heatwave to end.",
          f"  - Of the endings that happen under a storm, {_pct(a['share_exposed']['value'])} would not have "
          f"happened at the usual rate.",
          f"- **S1, the earlier era (1982–2001): {s1['verdict']}.** {_pct(s1['storm_share'])} of heatwave "
          f"water survived to D0 + 5 under storms against {_pct(s1['control_share'])} far away "
          f"({_ci(s1, scale=100, digits=0, unit=' points')}; {s1['n_points']} points, {s1['n_storms']} storms; "
          f"Holm p {_p(s1['p_holm'])}). With the control limited to the same 5° latitude band (D6) the "
          f"earlier era gives {_ci(ds['D6_band_control']['S1'], scale=100, digits=0, unit=' points')} (smaller, "
          f"and its interval includes zero); the whole "
          f"record gives {_ci(ds['D6_band_control']['survival 1982-2026'], scale=100, digits=0, unit=' points')}.",
          f"- **S2, return time: {s2['verdict']}.** Once a storm ends a heatwave, the next one arrives after "
          f"{s2['storm_days']:.0f} days on average, against {s2['control_days']:.0f} days for heatwaves that "
          f"ended on their own ({_ci(s2, digits=1, unit=' days')}; Holm p {_p(s2['p_holm'])}). **Not robust:** "
          f"with the control limited to the same 5° latitude band (D6) the difference is "
          f"{_ci(ds['D6_band_control']['S2'], digits=1, unit=' days')}, so storm-ended heatwaves return about "
          "as fast as others at the same latitude. Either way, storms do not keep heatwaves away for months.",
          f"- **S3, the next month: {s3['verdict']}.** Heatwave days over D0 + 6 to D0 + 35: "
          f"{_pct(s3['storm_occupancy'], 1)} under storms against {_pct(s3['control_occupancy'], 1)} expected "
          f"({_ci(s3, scale=100, digits=1, unit=' points')}, {s3['percent_of_control']:+.0f}% of the expected; "
          f"Holm p {_p(s3['p_holm'])}). The hold-back fades after the first month (D5: "
          f"{_ci(ds['D5_longer']['months 2-3'], scale=100, digits=1, unit=' points')} in months 2–3).",
          f"- **S4, storm power: {s4['verdict']}.** Survival difference per standard deviation of mixing power: "
          f"{s4['slope'] * 100:+.1f} points [{s4['lo'] * 100:+.1f}, {s4['hi'] * 100:+.1f}] (Holm p "
          f"{_p(s4['p_holm'])}).", ""]

    # ---- W1 detail
    L += ["## W1: the daily ending rate", "",
          "Hot cell-days are ocean cells in a heatwave on a day; an ending is a hot cell-day followed by a "
          "day out of the heatwave. A cell-day is exposed when a JTWC fix of 34 kt or more lies within 150 km "
          "on that day, the day before or the day after. Rates are compared within basin × month × 5° latitude "
          "strata (Mantel–Haenszel); intervals resample calendar years (95%).", "",
          "| Region | Hot cell-days | Endings | Share of hot cell-days under a storm | Ending rate, exposed | "
          "Ending rate, not | "
          "Rate ratio | Share of all endings due to storms | Verdict |",
          "| --- | ---: | ---: | ---: | ---: | ---: | --- | --- | --- |"]
    for reg, label in (("pooled", "Both"), ("north", "North"), ("south", "South")):
        r = prim[reg]
        x = r["all"]
        L.append(f"| {label} | {r['hot_cell_days']:,.0f} | {r['endings']:,.0f} | "
                 f"{_pct(x['exposed_share_of_days']['value'], 2)} | {_pct(x['rate_exposed']['value'], 1)} | "
                 f"{_pct(x['rate_unexposed']['value'], 1)} | {_vci(x['hr'])} | "
                 f"{_vci(x['share'], 100, 1, '%')} | {r['verdict']} |")
    L += ["", "By wind class (each against unexposed cell-days):", "",
          "| Region | 34–63 kt | 64 kt and above |", "| --- | --- | --- |"]
    for reg, label in (("pooled", "Both"), ("north", "North"), ("south", "South")):
        L.append(f"| {label} | {_vci(prim[reg]['34-63 kt']['hr'])} | {_vci(prim[reg]['64 kt and above']['hr'])} |")
    L += ["", "Sensitivity checks (rate ratio; share of all endings due to storms):", "",
          "| Variant | Both | North | South |", "| --- | --- | --- | --- |"]
    for v, r in w1.items():
        if v == "primary":
            continue
        cells = []
        for reg in ("pooled", "north", "south"):
            cells.append(f"{_vci(r[reg]['all']['hr'])}; {_vci(r[reg]['all']['share'], 100, 1, '%')}"
                         if reg in r else "—")
        L.append(f"| {v} | " + " | ".join(cells) + " |")
    L.append("")

    # ---- point tests
    c = pt["counts"]
    L += ["## The storm-point tests (S1–S4)", "",
          f"{c['points']:,} track points from {c['storms']} storms, 1982–2026 (JTWC ≥ 34 kt, ≥ 50 km from land); "
          f"{c['heatwave_points']:,} heatwave points from {c['heatwave_storms']} storms "
          f"({c['heatwave_points_by_era']['1982-2001']} in 1982–2001, {c['heatwave_points_by_era']['2002-2026']} "
          "in 2002–2026). Intervals resample whole storms (5,000 draws); Holm across the four.", "",
          "| Test | Estimate [95%] | Points (storms) | p | Holm p | Verdict |",
          "| --- | --- | --- | --- | --- | --- |",
          f"| S1 survival to D0+5, storm − far, 1982–2001 | {_ci(s1, scale=100, digits=1, unit=' pts')} | "
          f"{s1['n_points']} ({s1['n_storms']}) | {_p(s1['p'])} | {_p(s1['p_holm'])} | {s1['verdict']} |",
          f"| S2 return time, storm − far | {_ci(s2, digits=1, unit=' d')} | {s2['n_points']} ({s2['n_storms']}) | "
          f"{_p(s2['p'])} | {_p(s2['p_holm'])} | {s2['verdict']} |",
          f"| S3 heatwave days in month 1, storm − expected | {_ci(s3, scale=100, digits=1, unit=' pts')} | "
          f"{s3['n_points']} ({s3['n_storms']}) | {_p(s3['p'])} | {_p(s3['p_holm'])} | {s3['verdict']} |",
          f"| S4 survival per SD of mixing power | {s4['slope'] * 100:+.1f} pts [{s4['lo'] * 100:+.1f}, "
          f"{s4['hi'] * 100:+.1f}] | {s4['n_points']} ({s4['n_storms']}) | {_p(s4['p'])} | {_p(s4['p_holm'])} | "
          f"{s4['verdict']} |", ""]
    sa, s02 = pt["survival_all"], pt["survival_2002_2026"]
    L += [f"For reference, the same survival measure over 2002–2026 is {_ci(s02, scale=100, digits=1, unit=' pts')} "
          f"({s02['n_points']} points), and over the whole record {_ci(sa, scale=100, digits=1, unit=' pts')} "
          f"({_pct(sa['storm_share'])} under storms against {_pct(sa['control_share'])} far away).", ""]

    # ---- descriptive
    L += ["## Also reported (descriptive)", "", f"![Heatwave survival curves](figures/{f_surv.name})", ""]
    d1 = ds["D1_curve"]
    L.append("**D1, survival curve.** Storm minus far-away share still in a heatwave: " + "; ".join(
        f"D0+{j}: {_ci(e, scale=100, digits=0, unit=' pts')}" for j, e in zip((1, 5, 10, 20, 30), d1["difference"]))
        + ".")
    L += ["", f"![Storms over heatwave water per year](figures/{f_enc.name})", ""]
    for reg in ("north", "south"):
        e = ds["D2_encounters"][reg]
        ch = e["chance"]
        dec = ", ".join(f"{k}s: {v}" for k, v in sorted(e["by_decade"].items(), key=lambda kv: int(kv[0])))
        L.append(f"**D2, encounters ({reg}).** Storms over heatwave water per decade: {dec}. Theil–Sen trend "
                 f"{e['storms_per_decade']['slope']:+.1f} such storms a year, per decade "
                 f"[{e['storms_per_decade']['lo']:+.1f}, {e['storms_per_decade']['hi']:+.1f}]; share of points over "
                 f"heatwave water {100 * e['share_per_decade']['slope']:+.1f} points per decade. Storm discs held "
                 f"heatwave water on {_pct(ch['mean_E'], 1)} of their cells against {_pct(ch['mean_basin_share'], 1)} "
                 f"basin-wide on the same days ({_ci(ch, scale=100, digits=1, unit=' pts')}). A rise is expected "
                 "with a fixed baseline in a warming ocean.")
        L.append("")
    L += ["**D3, what changes the survival effect** (storm − far share at D0 + 5, 1982–2026):", "",
          "| Grouping | Level | Effect [95%] | Points (storms) |", "| --- | --- | --- | --- |"]
    for g, levels in ds["D3_modifiers"].items():
        if not isinstance(levels, dict):
            continue
        for lev, e in levels.items():
            L.append(f"| {g} | {lev} | {_ci(e, scale=100, digits=0, unit=' pts')} | {e['n_points']} ({e['n_storms']}) |")
    cuts = ds["D3_modifiers"]["pre-storm SST anomaly cut points"]
    L += ["", f"SST anomaly terciles cut at {cuts[0]:+.2f} and {cuts[1]:+.2f} °C.", ""]
    rec = ds["D4_recovery"]
    L.append("**D4, sea temperature recovery** (Kaplan–Meier median days until the disc's anomaly is back within "
             "0.2 °C of its pre-storm value; for heatwave points that value is the heatwave's own warmth): " + "; ".join(
                 f"{reg}: heatwave {_days(rec[reg]['heatwave']['median_days'])} ({rec[reg]['heatwave']['points']} pts), "
                 f"normal {_days(rec[reg]['normal']['median_days'])} ({rec[reg]['normal']['points']} pts)"
                 for reg in ("pooled", "north", "south")) + ".")
    L.append("")
    d5 = ds["D5_longer"]
    L.append("**D5, longer suppression** (heatwave days, storm − expected): " + "; ".join(
        f"{k}: {_ci(d5[k], scale=100, digits=1, unit=' pts')}"
        + (f" ({d5[k]['percent_of_control']:+.0f}%)" if "percent_of_control" in d5[k] else "")
        for k in ("months 2-3", "months 4-8", "heatwave points, month 1", "normal points, month 1")) + ".")
    L.append("")
    d6 = ds["D6_band_control"]
    L.append("**D6, control limited to the point's 5° latitude band:** " + "; ".join(
        f"{k}: {_ci(e, scale=(1 if k == 'S2' else 100), digits=1, unit=(' d' if k == 'S2' else ' pts'))}"
        for k, e in d6.items()) + ".")
    L += ["", "## Limits", "",
          "- Association, not proof: a storm's clouds, rain and wider wind field count as part of \"the storm\". "
          "The monsoon onset also ends heatwaves; the month strata address this but cannot remove it.",
          "- Track winds before about 2000 are less certain.",
          "- The fixed 1991–2020 baseline leaves fewer heatwaves in the 1980s, so S1 has fewer points.",
          "- OISST under-reads cold wakes under cloud, which hides some storm endings; this works against an effect.",
          ""]
    out = cfg.path("reports") / "heatwave_end.md"
    out.write_text("\n".join(L))
    return out
